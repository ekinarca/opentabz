export type InstrumentId = (typeof INSTRUMENT_IDS)[number];

export interface Instrument extends Omit<NewTrack, 'name' | 'shortName'> {
  readonly family: InstrumentFamily;
  /** The lowest and highest notes it plays (MIDI): an instrument with strings, from its open strings. */
  readonly range: readonly [number, number];
}

const GUITAR = [64, 59, 55, 50, 45, 40];

/** An instrument; one with strings plays from its lowest open string to 24 frets above its highest. */
function instrument(
  family: InstrumentFamily,
  program: number,
  options: {
    readonly tuning?: readonly number[];
    readonly clef?: TrackClef;
    readonly transposition?: number;
    readonly range?: readonly [number, number];
    readonly percussion?: boolean;
  } = {},
): Instrument {
  const tuning = options.tuning ?? [];
  const range: readonly [number, number] =
    options.range ?? (tuning.length > 0 ? [Math.min(...tuning), Math.max(...tuning) + 24] : [35, 81]);
  return {
    family,
    program,
    tuning,
    percussion: options.percussion ?? false,
    range,
    ...(options.clef === undefined ? {} : { clef: options.clef }),
    ...(options.transposition === undefined ? {} : { transposition: options.transposition }),
  };
}

