/**
 * The source of packages/core/src/print/music-glyphs.ts: the outline and advance of every SMuFL
 * symbol alphaTab can draw, read from Bravura's SVG font. Exports draw music symbols from these
 * outlines, so files need no font.
 */

export interface FontGlyph {
  readonly advance: number;
  readonly d: string;
}

const ENTITY = /^&#x([0-9a-f]+);$/i;

/** The glyphs of an SVG font, by code point. */
export function readSvgFont(svg: string): { unitsPerEm: number; glyphs: Map<number, FontGlyph> } {
  const unitsPerEm = Number(/units-per-em="(\d+)"/.exec(svg)?.[1] ?? Number.NaN);
  const defaultAdvance = Number(/<font\b[^>]*horiz-adv-x="([-\d.]+)"/.exec(svg)?.[1] ?? 0);
  const glyphs = new Map<number, FontGlyph>();
  for (const match of svg.matchAll(/<glyph\b([^>]*?)\/?>/gs)) {
    const attributes = match[1] ?? '';
    const unicode = /\sunicode="([^"]*)"/.exec(attributes)?.[1];
    if (unicode === undefined) continue;
    const entity = ENTITY.exec(unicode);
    const codePoint = entity === null ? unicode.codePointAt(0) : Number.parseInt(entity[1] ?? '', 16);
    if (codePoint === undefined || (entity === null && String.fromCodePoint(codePoint) !== unicode)) continue;
    const advance = Number(/horiz-adv-x="([-\d.]+)"/.exec(attributes)?.[1] ?? defaultAdvance);
    const d = (/\sd="([^"]*)"/s.exec(attributes)?.[1] ?? '').replace(/\s+/g, ' ').trim();
    glyphs.set(codePoint, { advance, d });
  }
  return { unitsPerEm, glyphs };
}

/** The module text: one line per symbol, `code advance path`, as Prettier prints it. */
export function musicGlyphsModule(fontSvg: string, codePoints: readonly number[]): string {
  const { unitsPerEm, glyphs } = readSvgFont(fontSvg);
  const wanted = [...new Set(codePoints)].sort((a, b) => a - b);
  const lines: string[] = [];
  for (const codePoint of wanted) {
    const glyph = glyphs.get(codePoint);
    if (glyph === undefined) throw new Error(`Bravura has no glyph for U+${codePoint.toString(16)}.`);
    lines.push(`  '${codePoint.toString(16)} ${glyph.advance} ${glyph.d}',`);
  }
  return [
    '/**',
    ' * Outlines of the SMuFL symbols alphaTab draws, from Bravura (Copyright (c) 2020, Steinberg Media',
    ' * Technologies GmbH, SIL Open Font License 1.1): `code point (hex), advance, SVG path data`, in font',
    ` * units (${unitsPerEm} per em, y up). Generated by packages/core/scripts/generate-music-glyphs.ts.`,
    ' */',
    `export const MUSIC_GLYPH_UNITS_PER_EM = ${unitsPerEm};`,
    '',
    'export const MUSIC_GLYPH_DATA: readonly string[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}
